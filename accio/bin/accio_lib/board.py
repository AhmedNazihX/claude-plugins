"""The board: story statuses, the ready list with stacking, board.md and status moves (DESIGN § 3.3, § 3.4, § 12.2).

During a build, a story's status lives in `run/status.json`, which overrides the status in its story file. `move`
only works during a build; outside one, the story file holds the status (`prophecy` and `owl` write it).
A parent that is ready, doing or in review in this run counts as in the batch, so its child stays listed with the
parent named; `brew` holds the child until the parent is READY (§ 3.4).
"""
import json
import subprocess
import os
import re
import tempfile

from accio_lib import paths, runlock, story

COLUMNS = (("backlog", "Backlog"), ("ready", "Ready"), ("doing", "Doing"),
           ("review", "Review"), ("done", "Done"), ("blocked", "Blocked"))
RUN_DIR_NAME = "run"
STATUS_NAME = runlock.STATUS_NAME
BOARD_NAME = "board.md"
STORY_FILE = re.compile(r"^S-(\d{3,})\.md$")
BOARD_HEADER = "# Board\n\nGenerated by `accio-board board`; never hand-edit.\n"
IN_RUN = ("ready", "doing", "review")


class BoardError(Exception):
    """A board problem, written for the user."""


def run_dir(accio):
    return accio / RUN_DIR_NAME


def stories_dir(accio):
    return accio / "stories"


def load_stories(accio):
    """Every story by id. Raises BoardError on a bad file, a duplicate id or a missing dependency."""
    found = {}
    for path in sorted(stories_dir(accio).glob("S-*.md")):
        try:
            parsed = story.parse(path)
        except story.StoryError as error:
            raise BoardError(str(error)) from error
        story_id = parsed.meta["id"]
        if path.stem != story_id:
            raise BoardError(f"{path}: the file name must match its id {story_id}")
        found[story_id] = parsed
    missing = sorted({(dep, sid) for sid, s in found.items() for dep in s.meta.get("deps", ()) if dep not in found})
    if missing:
        raise BoardError("; ".join(f"{sid} depends on {dep}, which has no story file" for dep, sid in missing))
    _check_cycles(found)
    return found


def _check_cycles(stories):
    state = {}

    def visit(story_id, trail):
        if state.get(story_id) == "done":
            return
        if state.get(story_id) == "visiting":
            raise BoardError(f"dependency cycle: {' -> '.join([*trail, story_id])}")
        state[story_id] = "visiting"
        for dep in stories[story_id].meta.get("deps", ()):
            visit(dep, [*trail, story_id])
        state[story_id] = "done"

    for story_id in stories:
        visit(story_id, [])


def read_overrides(accio):
    path = run_dir(accio) / STATUS_NAME
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}
    except (OSError, ValueError) as error:
        raise BoardError(f"{path} cannot be read: {error}") from error
    if not isinstance(data, dict):
        raise BoardError(f"{path} must hold a JSON object")
    bad = sorted(f"{key}: {value!r}" for key, value in data.items() if value not in story.STATUSES)
    if bad:
        raise BoardError(f"{path} has statuses that aren't one of {', '.join(story.STATUSES)}: {'; '.join(bad)}")
    return data


def statuses(stories, overrides):
    return {story_id: overrides.get(story_id, s.meta["status"]) for story_id, s in stories.items()}


def ready_batch(stories, status, stack_depth):
    """Ready stories in dependency order. A dep must be done, or a ready parent in the batch within stack_depth."""
    levels = {}

    def level(story_id):
        if story_id in levels:
            return levels[story_id]
        levels[story_id] = None
        parents = []
        for dep in stories[story_id].meta.get("deps", ()):
            if status[dep] == "done":
                continue
            if status[dep] not in IN_RUN or level(dep) is None:
                return None
            parents.append(dep)
        depth = 1 + max((levels[parent] for parent in parents), default=0)
        levels[story_id] = depth if depth <= stack_depth else None
        return levels[story_id]

    batch = [sid for sid in stories if status[sid] == "ready" and level(sid) is not None]
    batch.sort(key=lambda sid: (levels[sid], sid))
    return tuple(item(stories[sid], status, levels[sid]) for sid in batch)


def _git_ok(cwd, *args):
    try:
        result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=False)
    except OSError:
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def resume_point(main, accio, story_id, base_branch):
    """Where a story a crash left in *Doing* resumes (DESIGN § 12.6): `check` when its branch has commits after its
    base (the base accio-brief recorded, so a stacked child doesn't count its parent's commits; else the merge-base
    with the base branch), else `prepare`."""
    from accio_lib import checks  # checks imports merge, which imports this module
    branch = f"refs/heads/story/{story_id}"
    worktree = paths.worktree_root(main) / story_id
    recorded = checks.trusted_base(run_dir(accio) / story_id, worktree) if worktree.is_dir() else None
    base = recorded or _git_ok(main, "merge-base", base_branch, branch)
    count = _git_ok(main, "rev-list", "--count", f"{base}..{branch}") if base else None
    return "check" if count and int(count) > 0 else "prepare"


def resumed(stories, status, main, accio, base_branch):
    """The stories a crash left in *Doing*, each with where it resumes and its worktree, ahead of the ready ones."""
    return tuple({**item(stories[sid], status, 1), "resume": resume_point(main, accio, sid, base_branch),
                  "worktree": str(paths.worktree_root(main) / sid)}
                 for sid in sorted(stories) if status[sid] == "doing")


def item(parsed, status, level):
    deps = list(parsed.meta.get("deps", ()))
    return {"id": parsed.meta["id"], "title": parsed.meta["title"], "track": parsed.meta["track"],
            "deps": deps, "parents": [dep for dep in deps if status[dep] != "done"], "level": level}


def next_id(accio):
    numbers = [int(match.group(1)) for path in stories_dir(accio).glob("S-*.md")
               if (match := STORY_FILE.match(path.name))]
    return f"S-{max(numbers, default=0) + 1:03d}"


def move(accio, stories, story_id, new_status):
    """Record a status in run/status.json (never in the story file) and refresh the run lock."""
    if story_id not in stories:
        raise BoardError(f"there is no story {story_id}")
    if new_status not in story.STATUSES:
        raise BoardError(f"status must be one of {', '.join(story.STATUSES)}, got {new_status!r}")
    with runlock.guard(run_dir(accio)):
        if not runlock.lock_path(run_dir(accio)).exists():
            raise BoardError("move only runs during a build (no run lock exists); outside a build the story file holds the status")
        _write_json(run_dir(accio) / STATUS_NAME, {**read_overrides(accio), story_id: new_status})
        runlock.refresh(run_dir(accio))


def _write_json(path, data):
    """Write through a unique temp file and swap it in, so readers never see half a file."""
    try:
        handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
        with os.fdopen(handle, "w", encoding="utf-8") as stream:
            stream.write(json.dumps(data, indent=2, sort_keys=True) + "\n")
        os.replace(temporary, path)
    except OSError as error:
        raise BoardError(f"cannot write {path}: {error}") from error


def render(stories, status):
    """board.md: the six columns as a table, then the Dropped line."""
    cells = {key: [f"{sid} {stories[sid].meta['title']}" for sid in sorted(stories) if status[sid] == key]
             for key, _ in COLUMNS}
    height = max((len(column) for column in cells.values()), default=0)
    rows = ["| " + " | ".join(label for _, label in COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    for index in range(height):
        row = [cells[key][index] if index < len(cells[key]) else "" for key, _ in COLUMNS]
        rows.append("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |")
    dropped = [f"{sid} ({stories[sid].meta.get('dropped', 'no reason given')})"
               for sid in sorted(stories) if status[sid] == "dropped"]
    return f"{BOARD_HEADER}\n" + "\n".join(rows) + f"\n\nDropped: {', '.join(dropped) or 'none'}\n"


def summary(status):
    counts = {key: sum(1 for value in status.values() if value == key) for key in (*dict(COLUMNS), "dropped")}
    return "Board: " + " · ".join(f"{key} {count}" for key, count in counts.items())
