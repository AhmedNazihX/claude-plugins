class PrePushTest(HooksTestBase):
    def setUp(self):
        super().setUp()
        self.install()

    def lock(self, age_seconds=0):
        path = runlock.lock_path(self.run_dir)
        path.write_text("1\n")
        then = time.time() - age_seconds
        os.utime(path, (then, then))

    def token(self, sha):
        (self.run_dir / pushguard.TOKEN_NAME).write_text(sha + "\n")

    def test_S_012_5_a_live_build_blocks_a_tokenless_push_to_base_from_anyone(self):
        self.lock()
        self.new_commit()
        for claude in (False, True):
            result = self.push("main", claude=claude)
            self.assertNotEqual(result.returncode, 0, claude)
            self.assertIn("build is running", result.stderr)

    def test_S_012_5_a_live_build_still_allows_other_branches(self):
        self.lock()
        git(self.repo, "switch", "-q", "-c", "feature")
        self.new_commit()
        self.assertEqual(self.push("feature").returncode, 0)

    def test_S_012_5_a_push_of_several_refs_is_judged_ref_by_ref(self):
        git(self.repo, "switch", "-q", "-c", "feature")
        self.new_commit()
        git(self.repo, "switch", "-q", "main")
        self.new_commit("main-change.txt")
        result = self.push("feature", "main", claude=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("CLAUDECODE", result.stderr)

    def test_S_012_5_base_is_found_whatever_its_place_in_the_list(self):
        sha = self.new_commit()
        remote = self.remote_main()
        pushes = (pushguard.Push("refs/heads/feature", sha, "refs/heads/feature", "0" * 40),
                  pushguard.Push("refs/heads/main", sha, "refs/heads/main", remote))
        allowed, messages = pushguard.check_push(self.repo, self.repo / ".accio", self.repo, pushes,
                                                 {"CLAUDECODE": "1"})
        self.assertFalse(allowed)
        self.assertIn("CLAUDECODE", " ".join(messages))

    def test_S_012_6_a_story_worktree_never_pushes_to_base(self):
        worktree = self.story_worktree()
        self.new_commit(cwd=worktree)
        result = self.push("story/S-001:main", cwd=worktree)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("story worktree", result.stderr)
        self.assertEqual(self.push("story/S-001", cwd=worktree).returncode, 0)

    def test_S_012_6_story_worktrees_get_the_hooks_when_the_hooks_path_is_relative(self):
        for hooks_path in (".husky/_", ".githooks"):
            with self.subTest(hooks_path):
                if hooks_path == ".husky/_":
                    self.husky(project_lines="true\n")
                else:
                    git(self.repo, "config", "core.hooksPath", hooks_path)
                self.install()
                worktree, _ = brief.prepare_worktree(self.repo, self.run_dir / "S-001", "S-001",
                                                     git(self.repo, "rev-parse", "HEAD"))
                self.new_commit(f"wt-{hooks_path.replace('/', '-')}.txt", cwd=worktree)
                result = self.push("story/S-001:main", cwd=worktree)
                self.assertNotEqual(result.returncode, 0, result.stderr)
                self.assertIn("story worktree", result.stderr)
                git(self.repo, "worktree", "remove", "--force", str(worktree))
                git(self.repo, "branch", "-D", "story/S-001")

    def test_S_012_7_outside_a_run_claude_is_blocked_and_the_user_is_not(self):
        sha = self.new_commit()
        blocked = self.push("main", claude=True)
        self.assertNotEqual(blocked.returncode, 0)
        self.assertIn("CLAUDECODE", blocked.stderr)
        self.assertEqual(self.push("main").returncode, 0)
        self.assertEqual(self.remote_main(), sha)

