"""Native git hooks (DESIGN § 4.5, § 12.1; decisions 004, 009, 010): install with chaining, verify, uninstall.
The guards the hooks call are in `pushguard`.

accio's lines in a hook are always a pair, the `# accio` marker and one call line, so uninstall removes exactly
them. The call line names no local path (husky's hooks are committed): it runs the *helper*, `<git dir>/accio/hook`,
which never leaves this machine and holds the plugin's script and the repo's root. So a hook never has to find the
repo from wherever git was pointed (`git --work-tree=…` can't switch it off). A teammate without the helper skips
it quietly; where accio runs (`.accio/run/` exists) a missing helper or script stops Claude (`CLAUDECODE=1`) and
only warns the user, and `verify` writes them again.

- **Plain hooks folder:** the pair is appended (a hand-written shell hook keeps its lines first); a hook written in
  another language, or a symlink, is left alone with a message.
- **husky:** the pair goes in `.husky/<hook>`, after the project's lines.
- **lefthook, pre-commit framework** (their generated hook is in the active folder): accio edits nothing and prints
  a snippet. A config file alone (say for CI) doesn't count.
- **Relative `core.hooksPath`** (husky, `.githooks`): git looks for it inside each worktree, where it doesn't
  exist, so each story worktree gets the main checkout's folder as its own setting (`share_with_worktree`).
Install writes no allow rules anywhere (decision 010). Re-installing leaves the pair where it is.
"""
import dataclasses
import json
import os
import pathlib
import re
import shlex
import subprocess

HOOKS = ("pre-commit", "pre-push")
MARKER = "# accio"
SHEBANG = "#!/bin/sh"
SHELLS = ("sh", "bash", "dash", "zsh", "ksh")
HUSKY_FOLDER = ".husky"
HUSKY_HOOK_PATHS = (".husky", ".husky/_")
MANAGERS = (("pre-commit", "File generated by pre-commit", (".pre-commit-config.yaml", ".pre-commit-config.yml")),
            ("lefthook", "lefthook", ("lefthook.yml", "lefthook.yaml", ".lefthook.yml", ".lefthook.yaml",
                                      "lefthook.toml", "lefthook.json", "lefthook.jsonc", ".config/lefthook.yml",
                                      ".config/lefthook.yaml")))
PRE_PUSH_LEGACY = "pre-push.legacy"  # the pre-commit framework runs it first, with git's full list of refs
COMMAND_START = r"(?:^|[;&|(){]|\b(?:then|do|else|if)\b)\s*"
# `exit 1` and `exit $?` only run on failure, when git refuses anyway; `exec 1>&2` only redirects
EARLY_EXIT = re.compile(COMMAND_START + r"(?:exit(?:\s+0)?\s*(?:$|[;&|)}])|exec\s+(?![0-9]*[<>]))")
# a lone `read` takes part of git's list (`while read` takes all of it); `exec <` takes it away
REFS_READ = re.compile(COMMAND_START + r"(?:(?:\w+=\S*\s+)*read\b(?![^<]*<)|exec\s+0?<)")
EXECUTABLE = 0o111


class HooksError(Exception):
    """A hooks problem, written for the user."""


@dataclasses.dataclass(frozen=True)
class Layout:
    """`folder`: where accio's lines go (the active folder, for a manager); `config_file`: the manager's config."""
    kind: str
    folder: pathlib.Path
    config_file: pathlib.Path = None

    @property
    def is_manager(self):
        return self.kind in ("pre-commit", "lefthook")


@dataclasses.dataclass(frozen=True)
class Helper:
    script: str
    root: str


def run_git(cwd, *args):
    try:
        return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=False)
    except OSError as error:
        raise HooksError(f"git could not run in {cwd}: {error}") from error


def git_out(cwd, *args):
    result = run_git(cwd, *args)
    return result.stdout.strip() if result.returncode == 0 else None


# --- the call line and the helper ------------------------------------------------------------------------------

def call_line(hook):
    """The line accio adds to a hook: path-free, so a committed hook carries no one's folders."""
    helper = '"$accio_git/accio/hook"'
    return ('accio_git="$(git rev-parse --path-format=absolute --git-common-dir)"; '
            f'if [ -x {helper} ]; then {helper} {hook} "$@" || exit $?; '
            'elif [ "$CLAUDECODE" = 1 ] && [ -d "$accio_git/../.accio/run" ]; then '
            'echo "accio: its hook helper is missing; run accio-hooks install" >&2; exit 1; fi')


def parse_call(line):
    """The hook named in one of accio's call lines, or None."""
    return next((hook for hook in HOOKS if line == call_line(hook)), None)


def _calls(lines):
    """(index of the call line, its hook) for each accio pair."""
    pairs = ((index + 1, parse_call(lines[index + 1])) for index in range(len(lines) - 1) if lines[index] == MARKER)
    return tuple((index, hook) for index, hook in pairs if hook)


def helper_path(root):
    return pathlib.Path(git_out(root, "rev-parse", "--path-format=absolute", "--git-common-dir")) / "accio" / "hook"


def helper_text(script, root):
    quoted, where = shlex.quote(str(script)), shlex.quote(str(root))
    run_dir = shlex.quote(str(pathlib.Path(root) / ".accio" / "run"))
    return "\n".join((SHEBANG,
                      "# accio's hook helper, written by `accio-hooks install` and refreshed by `verify`. It lives in",
                      "# the git dir, so the paths below never reach a commit.",
                      'hook="$1"; shift',
                      f'if [ -x {quoted} ]; then exec {quoted} run "$hook" --root {where} "$@"; fi',
                      f"printf 'accio: %s is missing; run accio-hooks verify\\n' {quoted} >&2",
                      f'if [ "$CLAUDECODE" = 1 ] && [ -d {run_dir} ]; then exit 1; fi', ""))


def read_helper(root):
    """The script and root the helper calls, or None when it is missing or not accio's."""
    lines = _read_lines(helper_path(root)) or []
    words = next((shlex.split(line) for line in lines if line.startswith("if [ -x ")), [])
    return Helper(words[3], words[11]) if len(words) > 11 and words[10] == "--root" else None


def _write_helper(root, script):
    """Write the helper if it is missing or stale; returns a note, or None when it is current. A symlink at the
    helper's place, or for its folder, is refused rather than written through."""
    path, text = helper_path(root), helper_text(script, root)
    if path.is_symlink() or path.parent.is_symlink():
        raise HooksError(f"{path} is a symlink, so accio won't write through it; remove it and run "
                         "`accio-hooks install`.")
    try:
        current = path.read_text(encoding="utf-8") if path.exists() else None
    except (OSError, UnicodeDecodeError) as error:
        raise HooksError(f"cannot read {path}: {error}") from error
    if current == text:
        return None
    _write_lines(path, text.splitlines())
    return f"{'rewrote the stale plugin or repo path in' if current else 'wrote'} {path}"


# --- where the hooks live ---------------------------------------------------------------------------------------

def active_folder(root):
    """The hooks folder git runs now (core.hooksPath, or the common git dir's hooks)."""
    found = git_out(root, "rev-parse", "--path-format=absolute", "--git-path", "hooks")
    if found is None:
        raise HooksError(f"{root} is not a git repo")
    return pathlib.Path(found)


def _default_folder(root):
    return pathlib.Path(git_out(root, "rev-parse", "--path-format=absolute", "--git-common-dir")) / "hooks"


def layout(root):
    active = active_folder(root)
    for kind, stamp, configs in MANAGERS:
        if any(stamp in "\n".join(_read_lines(active / hook) or ()) for hook in HOOKS):
            return Layout(kind, active, next((root / name for name in configs if (root / name).is_file()), None))
    if active.resolve() in tuple((root / path).resolve() for path in HUSKY_HOOK_PATHS):
        return Layout("husky", root / HUSKY_FOLDER)
    return Layout("plain", active)


def _known_folders(found, root):
    """Every folder accio may have written to, active or not."""
    return tuple(dict.fromkeys((found.folder, _default_folder(root), root / HUSKY_FOLDER)))


def has_separate_git_dir(root):
    """A `git init --separate-git-dir` checkout: git keeps no record of it, so story worktrees can't find it."""
    if (root / ".git").is_dir() or not (root / ".git").exists():
        return False
    return git_out(root, "config", "core.worktree") is None


def share_with_worktree(root, worktree):
    """Point a story worktree at the main checkout's hooks folder when `core.hooksPath` is relative."""
    configured = git_out(root, "config", "--get", "core.hooksPath")
    if not configured or os.path.isabs(os.path.expanduser(configured)):
        return
    folder = active_folder(root)
    for cwd, args in ((root, ("config", "extensions.worktreeConfig", "true")),
                      (worktree, ("config", "--worktree", "core.hooksPath", str(folder)))):
        result = run_git(cwd, *args)
        if result.returncode != 0:
            raise HooksError(f"cannot point {worktree} at the hooks in {folder}: {result.stderr.strip()}")


# --- the marked lines -------------------------------------------------------------------------------------------

def _read_lines(path):
    try:
        return path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return None
    except (OSError, UnicodeDecodeError) as error:
        raise HooksError(f"cannot read {path}: {error}") from error


def _write_lines(path, lines):
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        path.chmod(path.stat().st_mode | EXECUTABLE)
    except OSError as error:
        raise HooksError(f"cannot write {path}: {error}") from error


def _interpreter(lines):
    words = lines[0][2:].split() if lines and lines[0].startswith("#!") else []
    if words and os.path.basename(words[0]) == "env":
        words = [word for word in words[1:] if not word.startswith("-")]
    return os.path.basename(words[0]) if words else "sh"


def _cannot_edit(path, hook):
    """Why accio won't add its lines to this hook file, or None."""
    if path.is_symlink():
        return (f"{path} is a symlink, so accio won't write through it. Add these two lines to the file it points "
                f"to yourself:\n{MARKER}\n{call_line(hook)}")
    interpreter = _interpreter(_read_lines(path) or [])
    if interpreter not in SHELLS:
        return (f"{path} is a {interpreter} script, so accio can't add its shell lines. Rename it to "
                f"{path.name}.local, call it from a new shell hook, and run `accio-hooks install` again.")
    return None


def _add(path, hook):
    lines = _read_lines(path)
    if lines and _calls(lines):
        return None
    _write_lines(path, [*(lines or [SHEBANG]), MARKER, call_line(hook)])
    return f"{'updated' if lines else 'wrote'} {path}"


def _remove(path):
    lines = _read_lines(path) if not path.is_symlink() else None
    if not lines or not _calls(lines):
        return None
    dropped = {index for call, _ in _calls(lines) for index in (call - 1, call)}
    kept = [line for index, line in enumerate(lines) if index not in dropped]
    try:
        if kept == [SHEBANG]:
            path.unlink()
        else:
            _write_lines(path, kept)
    except OSError as error:
        raise HooksError(f"cannot change {path}: {error}") from error
    return f"removed accio's lines from {path}"


# --- install, verify, uninstall ---------------------------------------------------------------------------------

def snippet(kind, root):
    helper = '"$(git rev-parse --path-format=absolute --git-common-dir)/accio/hook"'
    if kind == "lefthook":
        return (f"pre-commit:\n  commands:\n    accio:\n      run: {json.dumps(f'{helper} pre-commit')}\n"
                f"pre-push:\n  commands:\n    accio:\n      run: {json.dumps(f'{helper} pre-push')}\n"
                "      use_stdin: true\n")
    legacy = active_folder(root) / PRE_PUSH_LEGACY
    create = (f"printf '%s\\n' '{SHEBANG}' {shlex.quote(call_line('pre-push'))} > "
              f"{shlex.quote(str(legacy))} && chmod +x {shlex.quote(str(legacy))}")
    return ("repos:\n  - repo: local\n    hooks:\n"
            "      - id: accio-secrets\n        name: accio secret scan\n"
            f"        entry: {json.dumps('sh -c ' + shlex.quote(helper + ' pre-commit'))}\n"
            "        language: system\n        pass_filenames: false\n        always_run: true\n"
            "        stages: [pre-commit]\n"
            f"# For the push guard, pre-commit runs {PRE_PUSH_LEGACY} first with git's full list of refs:\n"
            f"#   {create}\n")


def install(root, script):
    """Install or refresh accio's hooks; returns (notes, problems)."""
    found = layout(root)
    notes = [note for note in (_write_helper(root, script),) if note]
    if found.is_manager:
        where = found.config_file.name if found.config_file else f"{found.kind}'s config"
        return (*notes, f"accio-hooks: {found.kind} manages this repo's hooks, so accio edits nothing. Add this to "
                        f"{where}:", snippet(found.kind, root)), ()
    problems = []
    for hook in HOOKS:
        path = found.folder / hook
        problem = _cannot_edit(path, hook) if path.exists() or path.is_symlink() else None
        if problem:
            problems.append(problem)
            continue
        notes.append(_add(path, hook) or f"{path} already has accio's lines")
        lines = _read_lines(path)
        problems += _skipped_lines(path, lines, _calls(lines), hook)
    if has_separate_git_dir(root):
        notes.append("accio-hooks: warning: this repo keeps its git folder elsewhere (`git init --separate-git-dir`), "
                     "so story worktrees aren't supported here: git doesn't record where this checkout is.")
    return tuple(notes), tuple(problems)


def _verify_manager(found, root):
    text = "\n".join(_read_lines(found.config_file) or ()) if found.config_file else ""
    has_push = found.kind == "lefthook" or bool(_calls(_read_lines(found.folder / PRE_PUSH_LEGACY) or []))
    if "/accio/hook" in text and has_push:
        return ()
    where = found.config_file or f"{found.kind}'s config"
    return (f"{where}: accio's hooks are missing or point at an old path. Add this (re-run `accio-hooks install` "
            f"to see it again), or carry on without accio's hooks:\n{snippet(found.kind, root)}",)


def _first_line(lines, pattern):
    """The 1-based number of the first line whose code (quotes and comments blanked) `pattern` finds, or None."""
    return next((number for number, line in enumerate(lines, 1) if pattern.search(_code(line))), None)


def _skipped_lines(path, lines, calls, hook):
    """Lines before accio's pair that can keep its check from running (decision: warn, the user moves them)."""
    before = lines[:calls[0][0] - 1]
    problems = []
    early = _first_line(before, EARLY_EXIT)
    if early:
        problems.append(f"{path}: line {early} (`{lines[early - 1].strip()}`) can end the hook before accio's {hook} "
                        "check runs. Move the `# accio` lines above it, or carry on without the check.")
    partial = hook == "pre-push" and _first_line(before, REFS_READ)
    if partial:
        problems.append(f"{path}: line {partial} (`{lines[partial - 1].strip()}`) reads git's list of refs (or part "
                        "of it) before accio does, so accio's push check can't see what is pushed. Read the whole list (a `while read` loop), and "
                        "accio stops a guarded push it can't see; or carry on without the check.")
    return problems


def _code(line):
    """The line with quoted text and comments blanked, so `echo "exit"` isn't taken for a command."""
    unquoted = re.sub(r"'[^']*'|\"(?:\\.|[^\"\\])*\"", '""', line)
    return re.sub(r"(?:^|\s)#.*$", "", unquoted)


def _hook_problems(path, lines, calls, hook):
    problems = [] if os.access(path, os.X_OK) else [
        f"{path} isn't executable, so git skips it. Run `accio-hooks install` (or `chmod +x {path}`)."]
    return problems + _skipped_lines(path, lines, calls, hook)


def verify(root, script):
    """(problems, fixes): problems need the user; fixes are what verify wrote (a missing or stale helper)."""
    active = active_folder(root)
    if active.exists() and not active.is_dir():
        return ((f"git's hooks are switched off: core.hooksPath points to {active}, which isn't a folder, so accio's "
                 "commit and push checks never run. Unset it (`git config --unset core.hooksPath`) and run "
                 "`accio-hooks install`, or carry on without them."),), ()
    found = layout(root)
    fixes = [fix for fix in (_write_helper(root, script),) if fix]
    if found.is_manager:
        return _verify_manager(found, root), tuple(fixes)
    problems = []
    for hook in HOOKS:
        path = found.folder / hook
        lines = _read_lines(path) or []
        calls = _calls(lines)
        if not calls:
            problems.append(_missing(found, root, hook, path))
            continue
        problems += _hook_problems(path, lines, calls, hook)
    return tuple(problems), tuple(fixes)


def _missing(found, root, hook, path):
    inactive = [folder for folder in _known_folders(found, root) if folder != found.folder
                and _calls(_read_lines(folder / hook) or [])]
    if inactive:
        return (f"{inactive[0]} has accio's {hook} hook but isn't the active hooks folder (git runs {found.folder}). "
                "Run `accio-hooks install` to add it there, or carry on without it.")
    return (f"{path}: accio's {hook} lines are missing. Run `accio-hooks install` to re-add them, "
            f"or carry on without accio's {hook} check.")


def uninstall(root):
    found = layout(root)
    folders = _known_folders(found, root)
    names = (*HOOKS, PRE_PUSH_LEGACY)
    notes = tuple(note for folder in folders for name in names if (note := _remove(folder / name)))
    helper = helper_path(root)
    try:
        if helper.exists():
            helper.unlink()
            if not any(helper.parent.iterdir()):
                helper.parent.rmdir()
            notes += (f"removed {helper}",)
    except OSError as error:
        raise HooksError(f"cannot remove {helper}: {error}") from error
    return notes
